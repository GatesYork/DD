test('operations can review fictional applicants, filter trips, and resolve a demo report', async ({ page }) => {
  await page.goto('http://localhost:3000');
  await expect(page.getByRole('heading', { name: 'A good night starts here.' })).toBeVisible();
  await page.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Driver reviews', exact: true }).click();
  await page.getByRole('button', { name: 'Approve Taylor Brooks', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('approved');
  await page.getByRole('button', { name: 'Trips', exact: true }).click();
  await page.getByLabel('Filter trips').selectOption('Cancelled');
  await expect(page.getByRole('cell', { name: 'DEMO-106', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: 'DEMO-104', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Support', exact: true }).click();
  await page.getByRole('button', { name: 'Resolve demo report', exact: true }).click();
  await expect(page.getByText('Resolved in this demo session')).toBeVisible();
});
